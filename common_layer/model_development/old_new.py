"""
old_new.py — the champion against the legacy forecaster on the same days (stage 10 of docs/Model_Development_Plan.pdf).

Before a target is switched from the legacy forecaster to the champion, both are scored on the same delivery days and hours
against the same outcomes, and the difference is tested (Diebold-Mariano on daily losses, as everywhere in the framework). The
result is a record, not a decision: switching is an edit of config/live_models.yaml.

`new_pred` is the champion's out-of-sample prediction table of a development run; `old_prices` holds what the legacy forecaster
returned for each delivery day ({day ordinal: {hour: price}}, hour 1 = first hour of the local day).
"""
from __future__ import annotations

from typing import Dict

import numpy as np
import pandas as pd

from common_layer.forecast_evaluation import metrics
from common_layer.forecast_evaluation.dm import diebold_mariano


def old_table(new_pred: pd.DataFrame, old_prices: Dict[int, Dict[int, float]]) -> pd.DataFrame:
    """The legacy forecasts laid out like the champion's table: same hours, same outcomes, y_pred from the legacy forecaster."""
    out = new_pred[["y_true", "local_date", "local_hour"]].copy()
    pos = new_pred.groupby("local_date").cumcount().to_numpy() + 1                 # hour 1, 2, ... of the delivery day
    out["y_pred"] = [old_prices.get(int(d), {}).get(int(h), np.nan) for d, h in zip(new_pred["local_date"], pos)]
    out["fold"] = 0
    return metrics.add_error_columns(out.dropna(subset=["y_true", "y_pred"]))


def compare(new_pred: pd.DataFrame, old_prices: Dict[int, Dict[int, float]], loss: str = "absolute", hac_lags: int = 7,
            small_sample: str = "hln") -> dict:
    """Scores of both on the days the legacy forecaster produced, and the test of new against old (negative = new is better)."""
    new = metrics.add_error_columns(new_pred.dropna(subset=["y_true", "y_pred"]))
    old = old_table(new, old_prices)
    new = new.loc[new.index.intersection(old.index)]
    old = old.loc[new.index]
    r = diebold_mariano(new, old, loss, hac_lags, small_sample)
    sn, so = metrics.score(new), metrics.score(old)
    out = {"days": int(new["local_date"].nunique()), "hours": int(len(new)), "loss": loss,
           "new": {k: float(sn[k]) for k in ("sse", "mae", "rmse")}, "old": {k: float(so[k]) for k in ("sse", "mae", "rmse")},
           "dm": {k: float(v) for k, v in r.items()}}
    out["mae_change"] = out["new"]["mae"] / out["old"]["mae"] - 1.0
    return out


def render(target: str, rep: dict, source: str) -> str:
    n, o, d = rep["new"], rep["old"], rep["dm"]
    verdict = ("the champion is significantly better" if d["p_value"] < 0.05 and d["mean_diff"] < 0 else
               "the legacy forecaster is significantly better" if d["p_value"] < 0.05 and d["mean_diff"] > 0 else "no significant difference")
    return "\n".join([f"# Champion against the legacy forecaster: {target}", "", "Generated by `tools/compare_old_new.py`; do not edit by hand.", "",
                      f"{rep['days']} delivery days, {rep['hours']:,} hours, the same outcomes for both. Test: Diebold-Mariano on daily {rep['loss']} loss.", "",
                      "| | SSE | MAE | RMSE |", "|---|---|---|---|",
                      f"| champion | {n['sse']:,.0f} | {n['mae']:.3f} | {n['rmse']:.3f} |",
                      f"| legacy | {o['sse']:,.0f} | {o['mae']:.3f} | {o['rmse']:.3f} |", "",
                      f"MAE change: {rep['mae_change']:+.1%}. Statistic {d['statistic']:.2f}, p = {d['p_value']:.3g}: **{verdict}**.", "",
                      f"Champion predictions from `{source}`. The legacy forecaster was run as it runs in the pipeline "
                      "(its own data and model selection), with the mode forced to legacy.", ""])
