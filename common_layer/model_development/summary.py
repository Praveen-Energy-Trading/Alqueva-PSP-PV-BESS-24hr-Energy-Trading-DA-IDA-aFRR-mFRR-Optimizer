"""
summary.py — one table of where every price target stands (stage 9 of docs/Model_Development_Plan.pdf).

Reads the files the earlier stages write: the champion decisions (model_development/selection/<target>.json), the locked-test
reports (model_development/locked_test/<target>.json) and the treatments in config/rollout.yaml, and the active champions of
the registry when it is given. The output is generated text; it depends only on those files, so a rerun gives the same text.
"""
from __future__ import annotations

import json
import os
from typing import Callable, Dict, List, Optional

import pandas as pd

from common_layer.model_development import rollout


def _read(path: str) -> Optional[dict]:
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def champion_text(c: Optional[dict]) -> str:
    if not c:
        return "-"
    return f"{c['method']} of {', '.join(c['members'])}" if c["type"] == "ensemble" else c["model"]


def collect(selection_dir: str, locked_dir: str, treatments: Optional[dict] = None,
            active_version: Optional[Callable[[str], Optional[int]]] = None) -> pd.DataFrame:
    """One row per price target."""
    r = treatments or rollout.load_rollout()
    rows: List[dict] = []
    for t in rollout.PRICE_TARGETS:
        d, lk = _read(os.path.join(selection_dir, f"{t}.json")), _read(os.path.join(locked_dir, f"{t}.json"))
        spec = r["targets"][t]
        row: Dict = {"target": t, "treatment": spec["treatment"], "feature_set": spec["feature_set"], "dev_days": None, "champion": "-",
                     "dev_mae": None, "vs_reference_p": None, "tied": "-", "locked_mae": None, "locked_vs_dev": None, "registered": "-"}
        if d:
            row.update(dev_days=d.get("n_days"), champion=champion_text(d.get("champion")) if d.get("champion") else d["status"],
                       dev_mae=d.get("champion_dev_loss"), tied=", ".join(d.get("tied", [])) or "-")
            if d.get("parsimony", {}).get("tested"):
                row["vs_reference_p"] = d["parsimony"]["p_value"]
        if lk:
            row.update(locked_mae=lk["locked_scores"]["mae"], locked_vs_dev=lk["loss_ratio_locked_over_dev"])
        if active_version:
            v = active_version(t)
            row["registered"] = f"v{v}" if v else "-"
        rows.append(row)
    return pd.DataFrame(rows)


def render(df: pd.DataFrame) -> str:
    def f(x, nd=3):
        return "" if x is None or (isinstance(x, float) and x != x) else f"{x:.{nd}f}"
    head = ["target", "treatment", "dev days", "champion", "dev MAE", "p vs reference", "tied with best", "locked MAE", "locked / dev", "registered"]
    out = ["# Where every price target stands", "", "Generated by `tools/make_results_summary.py` from the decision and locked-test files; do not edit by hand.",
           "Treatments are in `config/rollout.yaml`: `limited_evidence` targets have shorter histories and fewer development days; `deferred` "
           "targets could not be run honestly yet. An empty champion means no decision file exists yet. MAE is the mean daily absolute error "
           "(EUR/MWh, or EUR/MW/h for the aFRR capacity price).", "", "| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in df.itertuples():
        p = "" if r.vs_reference_p is None or r.vs_reference_p != r.vs_reference_p else f"{r.vs_reference_p:.2g}"
        out.append("| " + " | ".join([r.target, r.treatment, f(r.dev_days, 0), r.champion, f(r.dev_mae), p, r.tied, f(r.locked_mae), f(r.locked_vs_dev, 2),
                                      r.registered]) + " |")
    return "\n".join(out) + "\n"
