"""
select_champion.py — apply the champion selection policy to the tuned algorithms of a run (stage 5 of
docs/Model_Development_Plan.pdf).

    python tools/select_champion.py --run runtime/analysis/phase9/da_stage2_tpe --suffix _tuned --target da_price

Rule: config/model_selection.yaml. Writes model_development/selection/<target>.json (the decision, with every test and
reason, no time stamps) and <target>_decision.md, and records the decision in the experiment registry. The decision is
made on the development window only; it does not touch the locked test period.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir)))

from common_layer.forecast_evaluation.config import load_evaluation_config  # noqa: E402
from common_layer.model_development import evidence as ev  # noqa: E402
from common_layer.model_development import registry, selection  # noqa: E402

_REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))


def _rel(path: str) -> str:
    try:
        return os.path.relpath(path, _REPO).replace(os.sep, "/")
    except ValueError:
        return path.replace(os.sep, "/")


def render(d: dict, source: str) -> str:
    champ = d["champion"]
    if champ is None:
        what = "none (insufficient evidence)"
    elif champ["type"] == "single":
        what = f"**{champ['model']}**"
    else:
        what = f"the {champ['method']} of **{', '.join(champ['members'])}**"
    out = [f"# Champion decision: {d['target']}", "", "Generated by `tools/select_champion.py`; do not edit by hand.", "",
           f"**Champion: {what}**", "", f"Policy digest `{d['policy_digest'][:16]}` (config/model_selection.yaml). "
           f"{d['n_days']} delivery days, {d['n_hours']:,} hours, coverage {d['coverage']:.3f}.", "", "## Reasons", ""]
    out += [f"{i}. {r}" for i, r in enumerate(d["reasons"], 1)]
    if d.get("ranking"):
        t = pd.DataFrame(d["ranking"])
        out += ["", "## Ranking on the development window", "", "| model | mean loss | MAE | RMSE | SSE |", "|---|---|---|---|---|"]
        out += [f"| {r.model} | {r.mean_loss:.3f} | {r.mae:.3f} | {r.rmse:.3f} | {r.sse:,.0f} |" for r in t.itertuples()]
    if d.get("versus_best"):
        out += ["", f"## Each algorithm against the best ({d['best']})", "", "| model | statistic | p | p (Holm) | distinguishable |", "|---|---|---|---|---|"]
        out += [f"| {r['model']} | {r['statistic']:.2f} | {r['p_value']:.3g} | {r['p_holm']:.3g} | {r['distinguishable_from_best']} |"
                for r in d["versus_best"]]
    out += ["", f"Source predictions: `{source}`. The locked test period was not used."]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", required=True)
    ap.add_argument("--suffix", default="")
    ap.add_argument("--target", default="da_price")
    ap.add_argument("--policy", help="policy file (default config/model_selection.yaml)")
    ap.add_argument("--out", default=os.path.join(_REPO, "model_development", "selection"))
    ap.add_argument("--no-register", action="store_true")
    a = ap.parse_args()
    policy = selection.load_policy(a.policy)
    preds = ev.read_predictions(a.run, a.suffix)
    d = selection.select(preds, policy, load_evaluation_config()["comparison"], a.target)
    meta_path = os.path.join(a.run, "run.json")
    meta = json.load(open(meta_path, encoding="utf-8")) if os.path.exists(meta_path) else {}
    d["source"] = {"run": _rel(a.run), "suffix": a.suffix, "tuned": a.suffix == "_tuned",
                   "schedule": {k: meta.get(k) for k in ("retrain_every_days", "gap_days", "train_window_days")},
                   "window": [meta.get("test_start"), meta.get("test_end")]}
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, f"{a.target}.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(d, fh, indent=2, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(a.out, f"{a.target}_decision.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(d, f"{_rel(a.run)} (suffix {a.suffix})"))
    if not a.no_register:
        registry.record_selection(d, source=_rel(a.run))
    print(f"{a.target}: champion {d['champion']}")
    for r in d["reasons"]:
        print(" -", r)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
