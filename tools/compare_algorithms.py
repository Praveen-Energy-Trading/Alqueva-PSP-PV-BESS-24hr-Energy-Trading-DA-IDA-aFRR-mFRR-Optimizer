"""
compare_algorithms.py — compare the tree algorithms on the same days (stage 4 of docs/Model_Development_Plan.pdf).

    python tools/compare_algorithms.py --run runtime/analysis/phase9/da_stage2_tpe --suffix _tuned

Reads the predictions_<model><suffix>.csv files of a run folder and writes model_development/algorithm_comparison.md,
figures/algorithm_*.png and tables/algorithm_*.csv: scoreboard, all pairwise Diebold-Mariano tests with the Holm
correction, the algorithms that cannot be told apart from the best, and where each wins (hour, month, market regime).
The output depends only on the input folder, so rerunning gives the same files.
"""
from __future__ import annotations

import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir)))

from common_layer.forecast_evaluation.config import load_evaluation_config  # noqa: E402
from common_layer.market_analysis.config import load_analysis_config  # noqa: E402
from common_layer.model_development import comparison as cmp  # noqa: E402
from common_layer.model_development import comparison_figures as fig  # noqa: E402
from common_layer.model_development import evidence as ev  # noqa: E402

_REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))


def _rel(path: str) -> str:
    try:
        return os.path.relpath(path, _REPO).replace(os.sep, "/")
    except ValueError:
        return path.replace(os.sep, "/")


def _md(df: pd.DataFrame, digits: int = 3) -> str:
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda x: "" if pd.isna(x) else (f"{x:.2e}" if 0 < abs(x) < 1e-3 else f"{x:.{digits}f}"))
    head = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "|".join("---" for _ in d.columns) + "|"
    return "\n".join([head, sep] + ["| " + " | ".join(map(str, r)) + " |" for r in d.astype(str).to_numpy()])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", required=True, help="run folder with predictions_*.csv")
    ap.add_argument("--suffix", default="", help="file suffix of the predictions to use, e.g. _tuned")
    ap.add_argument("--models", nargs="*", help="subset and order of the algorithms (default: the five tree models)")
    ap.add_argument("--target", default="da_price")
    ap.add_argument("--label", default="algorithm", help="prefix of the output files (use it to keep two comparisons)")
    ap.add_argument("--out", default=os.path.join(_REPO, "model_development"))
    a = ap.parse_args()
    cfg = load_evaluation_config()["comparison"]
    order = a.models or ["decision_tree", "random_forest", "gradient_boosting", "xgboost", "lightgbm"]
    preds = ev.read_predictions(a.run, a.suffix)
    missing = [m for m in order if m not in preds]
    if missing:
        raise SystemExit(f"no predictions for {missing} in {a.run} (suffix {a.suffix!r})")
    prep = cmp.prepare({m: preds[m] for m in order})
    figs, tabs = os.path.join(a.out, "figures"), os.path.join(a.out, "tables")
    os.makedirs(tabs, exist_ok=True)
    pre = a.label

    board = cmp.scoreboard(prep)
    pairs = cmp.pairwise(prep, cfg["loss"], cfg["hac_lags"], cfg["small_sample"])
    vb = cmp.versus_best(prep, cfg["loss"], cfg["hac_lags"], cfg["small_sample"])
    tops = cmp.top_set(vb)
    stat, pho = cmp.matrix(pairs, order), cmp.matrix(pairs, order, "p_holm")
    board.to_csv(os.path.join(tabs, f"{pre}_scoreboard.csv"), index=False, float_format="%.4f")
    pairs.to_csv(os.path.join(tabs, f"{pre}_pairwise_dm.csv"), index=False, float_format="%.6g")
    vb.to_csv(os.path.join(tabs, f"{pre}_versus_best.csv"), index=False, float_format="%.6g")

    n_hours = int(board["n"].iloc[0])
    out = [f"# Algorithm comparison: {a.target}, development window", "",
           "Generated by `tools/compare_algorithms.py`; do not edit by hand.", "",
           f"Algorithms: {', '.join(order)}. All are scored on the same {n_hours:,} hours. Loss for the tests: {cfg['loss']} error, "
           f"daily differences, Newey-West variance with {cfg['hac_lags']} lags, Harvey-Leybourne-Newbold correction. A negative "
           "statistic means the first algorithm has the smaller loss.", "",
           "## 1. Scoreboard", "", "`days_best` is the share of delivery days on which the algorithm had the smallest daily MAE.", "",
           _md(board), "",
           "## 2. Every pair, with the Holm correction", "",
           f"![dm matrix](figures/{os.path.basename(fig.dm_heatmap(stat, pho, figs, f'{pre}_dm_matrix.png'))})", "",
           f"{int(pairs['significant'].sum())} of {len(pairs)} pairs differ significantly at 5% after the Holm correction.", "",
           _md(pairs[["a", "b", "n_days", "mean_loss_a", "mean_loss_b", "statistic", "p_value", "p_holm", "better"]]), "",
           "## 3. Which algorithms cannot be told apart from the best", "",
           f"Best by mean loss: **{vb['best'].iloc[0]}**. Not distinguishable from it (Holm over the {len(vb)} comparisons with the "
           f"best): **{', '.join(tops)}**.", "",
           _md(vb[["model", "mean_loss", "best_loss", "mean_diff", "statistic", "p_value", "p_holm", "distinguishable_from_best"]]), ""]

    hour = cmp.win_table(prep, "hour")
    month = cmp.win_table(prep, "month")
    regime = cmp.win_table(prep, "regime", load_analysis_config()["periods"])
    for name, t in (("hour", hour), ("month", month), ("regime", regime)):
        t.to_csv(os.path.join(tabs, f"{pre}_by_{name}.csv"), index=False, float_format="%.4f")
    out += ["## 4. Where each algorithm wins", "",
            f"![by hour](figures/{os.path.basename(fig.mae_by_hour(hour, order, figs, f'{pre}_mae_by_hour.png'))})", "",
            "`lowest_mae` is the algorithm with the smallest average error in the group; `winner` is the one that was best in the "
            "most units and `winner_share` the share of units it won (a unit is one day-hour for the hour table, one delivery day "
            "otherwise). The two can differ.", "",
            "### By month of the year", "",
            f"![by month](figures/{os.path.basename(fig.mae_by_group(month, order, figs, f'{pre}_mae_by_month.png', 'month'))})", "",
            _md(month), "", "### By market regime", "",
            f"![by regime](figures/{os.path.basename(fig.mae_by_group(regime, order, figs, f'{pre}_mae_by_regime.png', 'market regime'))})", "",
            _md(regime), "", "### By hour of day", "", _md(hour), "", f"Source run: `{_rel(a.run)}` (suffix `{a.suffix}`)."]
    with open(os.path.join(a.out, f"{pre}_comparison.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {os.path.join(a.out, f'{pre}_comparison.md')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
