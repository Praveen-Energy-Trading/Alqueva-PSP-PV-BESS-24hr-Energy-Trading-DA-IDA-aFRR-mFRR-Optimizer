"""
make_tuning_evidence.py — figures and tables of what the hyperparameter tuning did (stage 3 of docs/Model_Development_Plan.pdf).

    python tools/make_tuning_evidence.py --tpe runtime/analysis/phase9/da_stage2_tpe \\
        --random runtime/analysis/phase9/da_stage2_random --untuned runtime/analysis/phase9/da_untuned

Reads the files that `tools/evaluate_forecaster.py --tuned` writes (tuning_trials.csv, tuning_log.csv, predictions_*.csv) and
writes model_development/tuning_evidence.md, model_development/figures/*.png and model_development/tables/*.csv. The
output depends only on the input folders, so rerunning it gives the same files.
"""
from __future__ import annotations

import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir)))

from common_layer.model_development import evidence as ev  # noqa: E402
from common_layer.model_development import evidence_figures as fig  # noqa: E402

_REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))


def _rel(path: str) -> str:
    try:
        return os.path.relpath(path, _REPO).replace(os.sep, "/")
    except ValueError:                                  # another drive
        return path.replace(os.sep, "/")


def _md(df: pd.DataFrame, digits: int = 3) -> str:
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda x: "" if pd.isna(x) else f"{x:.{digits}f}")
    head = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "|".join("---" for _ in d.columns) + "|"
    return "\n".join([head, sep] + ["| " + " | ".join(map(str, r)) + " |" for r in d.astype(str).to_numpy()])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tpe", required=True, help="run folder of the Optuna search")
    ap.add_argument("--random", required=True, help="run folder of the random-search control (same budget)")
    ap.add_argument("--untuned", help="run folder of the untuned models (for the outer gain over the defaults)")
    ap.add_argument("--out", default=os.path.join(_REPO, "model_development"))
    ap.add_argument("--target", default="da_price")
    a = ap.parse_args()
    figs, tabs = os.path.join(a.out, "figures"), os.path.join(a.out, "tables")
    os.makedirs(tabs, exist_ok=True)

    tr = {"tpe": ev.load_trials(a.tpe), "random": ev.load_trials(a.random)}
    logs = {k: pd.read_csv(os.path.join(p, "tuning_log.csv")) for k, p in (("tpe", a.tpe), ("random", a.random))}
    curves = {k: ev.best_so_far(v) for k, v in tr.items()}
    out = [f"# Tuning evidence: {a.target}, development window", "",
           "Generated by `tools/make_tuning_evidence.py` from the trial logs of the runs named below; do not edit by hand.",
           "Scores are mean absolute error in price units; a *relative score* is a trial's score divided by the score of the "
           "algorithm's defaults in the same tuning round (below 1 beats the defaults).", ""]

    # 1. convergence
    p = fig.convergence(curves, figs)
    rows = []
    for k, c in curves.items():
        for m, g in c.groupby("model"):
            at = lambda n: float(g[g["trial"] <= n]["best_rel"].iloc[-1])      # noqa: E731
            rows.append({"search": k, "model": m, "after 10 trials": at(10), "after 20": at(20), "after 40": at(39),
                         "rounds": int(g["rounds"].max())})
    conv = pd.DataFrame(rows).sort_values(["model", "search"])
    conv.to_csv(os.path.join(tabs, "convergence.csv"), index=False, float_format="%.4f")
    out += ["## 1. How fast the search converges", "", f"![convergence](figures/{os.path.basename(p)})", "",
            "Best relative score after k trials, mean over the tuning rounds (one line per search method, same budget).", "",
            _md(conv), ""]

    # 2. importance and effects (random run: uniformly drawn trials)
    imp = pd.concat([ev.importance(tr["random"], m) for m in sorted(tr["random"]["model"].unique())], ignore_index=True)
    imp.to_csv(os.path.join(tabs, "importance_random_search.csv"), index=False, float_format="%.4f")
    out += ["## 2. Which settings matter", "", f"![importance](figures/{os.path.basename(fig.importance_bars(imp, figs))})", "",
            "Share of the variance of the relative score explained by each setting, from the uniformly drawn trials of the "
            "random-search control (marginal, not an interaction analysis).", ""]
    for m in sorted(tr["random"]["model"].unique()):
        eff = ev.effects(tr["random"], m)
        eff.to_csv(os.path.join(tabs, f"effects_{m}.csv"), index=False, float_format="%.4f")
        if len(eff):
            out += [f"![effects {m}](figures/{os.path.basename(fig.setting_effects(eff, m, figs))})", ""]

    # 3. what was chosen, and how stable
    sel = {k: ev.selected_settings(v) for k, v in logs.items()}
    stab = pd.concat([ev.stability(sel[k]).assign(search=k) for k in sel], ignore_index=True)
    stab.to_csv(os.path.join(tabs, "stability.csv"), index=False, float_format="%.4f")
    sel_wide = pd.concat([sel[k].assign(search=k) for k in sel], ignore_index=True)
    sel_wide.to_csv(os.path.join(tabs, "selected_settings.csv"), index=False)
    out += ["## 3. What was chosen, and how stable it is", "",
            "Share of tuning rounds that chose the most frequent value of a setting (1.0 = the same value every round).", "",
            _md(stab[["search", "model", "setting", "rounds", "most_frequent", "share_most_frequent"]]), ""]

    # 4. inner against outer
    tuned_pred = {k.replace("_tuned", ""): v for k, v in ev.read_predictions(a.tpe, "_tuned").items()}
    default_pred = ev.read_predictions(a.untuned) if a.untuned else None
    io = ev.inner_vs_outer(logs["tpe"], tuned_pred, default_pred)
    io.to_csv(os.path.join(tabs, "inner_vs_outer_tpe.csv"), index=False, float_format="%.4f")
    summ = io.groupby("model").agg(inner_gain=("inner_gain", "mean"), outer_gain=("outer_gain", "mean"),
                                   mean_gap=("gap", "mean"), rounds=("tuned_at", "size")).reset_index()
    out += ["## 4. The gain seen when choosing against the gain afterwards", "",
            f"![inner vs outer](figures/{os.path.basename(fig.inner_outer(io, figs))})", "",
            "Inner = gain of the chosen setting over the defaults on the validation blocks it was chosen on. Outer = gain on the "
            "days that then used it (compared with the untuned model on the same days). Gap = outer MAE of the tuned model "
            "minus the inner score.", "", _md(summ), ""]

    # 5. pruning
    pr = ev.pruning_summary(tr["tpe"])
    pr.to_csv(os.path.join(tabs, "pruning_tpe.csv"), index=False, float_format="%.4f")
    out += ["## 5. Pruning in the Optuna search", "", _md(pr), ""]
    out += ["## Source runs", "", f"- Optuna: `{_rel(a.tpe)}`", f"- random control: `{_rel(a.random)}`"]
    if a.untuned:
        out.append(f"- untuned: `{_rel(a.untuned)}`")
    with open(os.path.join(a.out, "tuning_evidence.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {os.path.join(a.out, 'tuning_evidence.md')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
